#!/usr/bin/env bash
set -euo pipefail
root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
python3 -m py_compile "$root/pm-process-site-partials"
bash -n "$root/pm-helpers-node"
grep -Fq 'is_derived_localized_output(path)' "$root/pm-process-site-partials"
grep -Fq 'pm_node_verify_localized_outputs()' "$root/pm-helpers-node"
grep -Fq 'pm_runtime_verify_build_inputs()' "$root/pm-helpers-node"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/public/partials" "$tmp/public/locales/es-ES" "$tmp/content/en-US" "$tmp/content/es-ES"
printf '%s\n' '[{"locale":"en-US","direction":"ltr"},{"locale":"es-ES","direction":"ltr"}]' > "$tmp/content/locales.json"
printf '%s\n' '{"nav":{"how":"How"}}' > "$tmp/content/en-US/public.json"
printf '%s\n' '{"nav":{"how":"Cómo"}}' > "$tmp/content/es-ES/public.json"
printf '%s\n' 'SITE_LABEL=Rendered' > "$tmp/.env.generated"
printf '%s\n' '<header>${SITE_LABEL} [[copy:public.nav.how]]</header>' > "$tmp/public/partials/header.html"
printf '%s\n' '<html lang="en"><body><!-- PM:header --><header>template-old</header><!-- /PM:header --><p>{{ENV:SITE_LABEL}}</p></body></html>' > "$tmp/public/site.template.html"
printf '%s\n' '<!-- PM:header --><header>standalone-old</header><!-- /PM:header -->' > "$tmp/public/standalone.html"
printf '%s\n' '<!-- PM:header --><header>Resolved English</header><!-- /PM:header -->' > "$tmp/public/index.html"
printf '%s\n' '<!-- PM:header --><header>Resuelto Espanol</header><!-- /PM:header -->' > "$tmp/public/locales/es-ES/index.html"
(
  cd "$tmp"
  python3 "$root/pm-process-site-partials" >/dev/null
)
grep -Fq '<header>Rendered [[copy:public.nav.how]]</header>' "$tmp/public/site.template.html"
grep -Fq '<p>Rendered</p>' "$tmp/public/site.template.html"
grep -Fq '<header>Rendered [[copy:public.nav.how]]</header>' "$tmp/public/standalone.html"
grep -Fq 'Resolved English' "$tmp/public/index.html"
grep -Fq 'Resuelto Espanol' "$tmp/public/locales/es-ES/index.html"
if grep -Fq '[[copy:' "$tmp/public/index.html" "$tmp/public/locales/es-ES/index.html"; then
  echo 'partial processing corrupted a generated localized index' >&2
  exit 1
fi
(
  cd "$tmp"
  export PORTMASON_SHARE="$root" PROJECT_ROOT="$tmp" SITE_ROOT="$tmp/public"
  log() { :; }
  die() { printf 'ERROR: %s\n' "$1" >&2; return "${2:-1}"; }
  . "$root/pm-helpers-node"
  pm_web_validate_locale_catalogs
  pm_node_deploy_public_site
)
grep -Fq '<header>Rendered How</header>' "$tmp/public/index.html"
grep -Fq '<header>Rendered Cómo</header>' "$tmp/public/locales/es-ES/index.html"
grep -Fq 'lang="es-ES" dir="ltr" data-locale="es-ES"' "$tmp/public/locales/es-ES/index.html"
grep -Fq 'Generated by Portmason pm-helpers-node' "$tmp/public/content.generated.js"
if rg -n '\[\[copy:|\{\{ENV:|\$\{' "$tmp/public/index.html" "$tmp/public/locales/es-ES/index.html"; then
  echo 'localized output contains an unresolved token' >&2
  exit 1
fi
echo 'PASS: Portmason owns partial rendering, environment substitution, and localization'
